export const getMockItemBySegment = (segment: string, id: string) => {
  const items = mockFinder[segment as keyof typeof mockFinder];

  if (!items) {
    return null;
  }

  const normalizedId = normalize(id);

  return items.find((item) => {
    const record = item as Record<string, unknown>;
    return [
      record.id,
      record.display_id,
      record.generated_id,
      record.request_code,
      record.order_number,
    ].some((value) => normalize(value) === normalizedId);
  }) ?? null;
};
