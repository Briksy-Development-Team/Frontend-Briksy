type ListParams = {
  page?: number;
  per_page?: number;
  search?: string;
  sort?: string;
  direction?: "asc" | "desc";
  filters?: Record<string, unknown>;
};

const daysAgo = (days: number) => new Date(Date.now() - days * 24 * 60 * 60 * 1000).toISOString();
const monthsAgo = (months: number) => {
  const date = new Date();
  date.setMonth(date.getMonth() - months);
  return date.toISOString();
};

const normalize = (value: unknown) => String(value ?? "").trim().toLowerCase();

const getPathValue = (item: Record<string, unknown>, path: string): unknown =>
  path.split(".").reduce<unknown>((current, key) => {
    if (current && typeof current === "object") {
      return (current as Record<string, unknown>)[key];
    }

    return undefined;
  }, item);

const matchesSearch = (item: Record<string, unknown>, fields: string[], search?: string) => {
  const query = normalize(search);

  if (!query) {
    return true;
  }

  return fields.some((field) => normalize(getPathValue(item, field)).includes(query));
};

const matchesFilter = (itemValue: unknown, filterValue: unknown) => {
  if (filterValue === undefined || filterValue === null || filterValue === "") {
    return true;
  }

  if (Array.isArray(filterValue)) {
    return filterValue.some((value) => normalize(value) === normalize(itemValue));
  }

  if (typeof filterValue === "boolean") {
    return Boolean(itemValue) === filterValue;
  }

  if (typeof filterValue === "object") {
    const range = filterValue as { min?: number; max?: number; from?: string; to?: string };
    const numericValue = Number(itemValue);

    if (range.min !== undefined || range.max !== undefined) {
      if (Number.isNaN(numericValue)) {
        return false;
      }

      if (range.min !== undefined && numericValue < range.min) {
        return false;
      }

      if (range.max !== undefined && numericValue > range.max) {
        return false;
      }

      return true;
    }

    if (range.from || range.to) {
      const itemDate = itemValue ? new Date(String(itemValue)).getTime() : NaN;
      
      let fromTime = Number.NEGATIVE_INFINITY;
      if (range.from) {
        const d = new Date(range.from);
        d.setHours(0, 0, 0, 0);
        fromTime = d.getTime();
      }

      let toTime = Number.POSITIVE_INFINITY;
      if (range.to) {
        const d = new Date(range.to);
        d.setHours(23, 59, 59, 999);
        toTime = d.getTime();
      }

      if (Number.isNaN(itemDate)) {
        return false;
      }

      return itemDate >= fromTime && itemDate <= toTime;
    }
  }

  if (typeof itemValue === "string") {
    return normalize(itemValue).includes(normalize(filterValue));
  }

  return normalize(itemValue) === normalize(filterValue);
};

const sortRecords = <T extends Record<string, unknown>>(
  items: T[],
  sort?: string,
  direction: "asc" | "desc" = "asc",
) => {
  if (!sort) {
    return items;
  }

  const sign = direction === "desc" ? -1 : 1;

  return [...items].sort((left, right) => {
    const a = getPathValue(left, sort);
    const b = getPathValue(right, sort);

    const aNum = Number(a);
    const bNum = Number(b);

    if (!Number.isNaN(aNum) && !Number.isNaN(bNum)) {
      return (aNum - bNum) * sign;
    }

    return normalize(a).localeCompare(normalize(b)) * sign;
  });
};

const paginate = <T>(items: T[], params?: ListParams) => {
  const page = Math.max(1, params?.page ?? 1);
  const perPage = Math.max(1, params?.per_page ?? 10);
  const start = (page - 1) * perPage;

  return items.slice(start, start + perPage);
};

export const queryMockList = <T extends Record<string, unknown>>(
  items: T[],
  params?: ListParams,
  options?: {
    searchFields?: string[];
    filterKeys?: string[];
  },
) => {
  const searchFields = options?.searchFields ?? ["name", "title", "email", "company.name", "order_number"];
  const getFilterPath = (key: string) => {
    if (key === "type_slug") {
      return "type.slug";
    }

    return key;
  };

  const filtered = items.filter((item) => {
    if (!matchesSearch(item, searchFields, params?.search)) {
      return false;
    }

    return Object.entries(params?.filters ?? {}).every(([key, value]) => {
      if (options?.filterKeys && !options.filterKeys.includes(key)) {
        return true;
      }

      return matchesFilter(getPathValue(item, getFilterPath(key)), value);
    });
  });

  const sorted = sortRecords(filtered, params?.sort, params?.direction ?? "asc");

  return {
    data: paginate(sorted, params),
    total: sorted.length,
  };
};

